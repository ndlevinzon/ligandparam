    @classmethod
    def from_parmed(cls,mol):
        from . constants import GetAtomicSymbol
        from collections import defaultdict as ddict
        data = {}
        data["positions"] = []
        data["names"] = []
        data["types"] = []
        data["elements"] = []
        data["charges"] = []
        data["residxs"] = []
        resnames = ddict(str)
        q = 0
        for a in mol.atoms:
            data["positions"].append( [a.xx,a.xy,a.xz] )
            data["names"].append(a.name)
            data["types"].append(a.type)
            data["elements"].append( GetAtomicSymbol(a.element) )
            data["charges"].append(a.charge)
            data["residxs"].append(a.residue.idx)
            resnames[a.residue.idx] = a.residue.name
            q += a.charge
        data["resnames"] = dict(resnames)
        data["spin"] = 1
        #data["charge"] = int(round(q))
        data["bonds"] = []
        for x in mol.bonds:
            data["bonds"].append( [x.atom1.idx, x.atom2.idx ] )
        data["parm"] = None
        data["constraints"] = []
        data["restraints"] = []
        data["name"] = "s000"
        data["energy"] = None
        data["forces"] = None
        
        from collections import defaultdict as ddict
        names = data["names"]
        seen = ddict(int)
        for iname in range(len(names)):
            name = names[iname]
            if name in seen:
                for i in range(98):
                    j=i+1
                    tname = "%s%i"%(name,j)
                    if tname in seen or tname in names:
                        continue
                    else:
                        break
                seen[tname] += 1
                names[iname] = tname
        data["names"] = names
        
        return cls(data)

    
