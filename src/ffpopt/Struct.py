    @classmethod
    def from_rdkit(cls,mol):
        import numpy as np
        from collections import defaultdict as ddict
        from rdkit import Chem
        from rdkit.Chem import AllChem
        
        eles = [atom.GetSymbol() for atom in mol.GetAtoms()]
        try:
            conf = mol.GetConformer()
        except:
            status = AllChem.EmbedMolecule(mol, randomSeed=42)
            conf = mol.GetConformer()

        coords = conf.GetPositions()
        net_charge = Chem.GetFormalCharge(mol)
        qs = [net_charge/len(eles)]*len(eles)
        bonds = [(bond.GetBeginAtomIdx(), bond.GetEndAtomIdx()) for bond in mol.GetBonds()]
        data = {}
        data["positions"] = coords.tolist()
        data["names"] = eles
        data["types"] = eles
        data["elements"] = eles
        data["charges"] = qs

        resnames = ddict(str)
        residxs = []
        for atom in mol.GetAtoms():
            res_info = atom.GetPDBResidueInfo()
            if res_info:
                idx = res_info.GetResidueIndex()
                residxs.append( idx )
                resnames[idx] = res_info.GetResidueName()
            else:
                residxs.append(0)
                resnames[0] = "MOL"
        data["residxs"] = residxs
        data["resnames"] = dict(resnames)
        data["spin"] = 1
        #data["charge"] = int(round(net_charge))
        data["bonds"] = bonds
        data["parm"] = None
        data["constraints"] = []
        data["restraints"] = []
        data["name"] = "s000"
        data["energy"] = None
        data["forces"] = None

        return cls(data)


