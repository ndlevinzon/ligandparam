    @classmethod
    def from_file(cls,filename):
        ss = None
        try:
            import json
            fh = open(filename,'r')
            data = json.load(fh)
            ss = [Struct(x) for x in data]
        except Exception as JsonError:
            try:
                ss = [ Struct.from_mol2(filename) ]
            except Exception as Mol2Error:
                raise Exception(JsonError)
        return cls( ss )

    

