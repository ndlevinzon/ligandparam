    def GetRDKitAtoms(self):
        """
        Return a copy of the molecule using the RDKit molecule class

        Parameters
        ----------
        None
        
        Returns
        -------
        mol : RDKit molecule
        """
        from rdkit.Chem import MolFromMol2Block
        from rdkit import rdBase
        from rdkit.Chem import SanitizeMol
        from rdkit.Chem import GetFormalCharge
        from rdkit.Chem import rdDetermineBonds
        from rdkit.Chem import AtomPDBResidueInfo # <-- Import the metadata class
        from io import StringIO

        mol = self.GetParmedAtoms()
        for i,a in enumerate(mol.atoms):
            a.type = self.data["elements"][i]
            
        rdBase.DisableLog('rdApp.warning')
        rdBase.DisableLog('rdApp.error')

        mol2str = StringIO()
        mol.save(mol2str,format="MOL2")
        mol2str = mol2str.getvalue()
        mol = MolFromMol2Block(mol2str, removeHs=False, sanitize=False )

        for atom in mol.GetAtoms():
            atom.SetFormalCharge(0)
        rdDetermineBonds.DetermineBondOrders(mol, charge=self.GetCharge())
        
        SanitizeMol(mol)
        rdBase.EnableLog('rdApp.warning')
        rdBase.EnableLog('rdApp.error')

        # --- Inject Residue Information into the final RDKit Molecule ---
        eles = self.data["elements"]
        res_indices = self.data.get("residxs", [0] * len(eles))
        res_names_dict = self.data.get("resnames", {0: "MOL"})
        names = self.data.get("names", eles)

        for i, atom in enumerate(mol.GetAtoms()):
            # 1. Gather raw data matching this atom's order index
            atom_name = names[i]
            res_idx = int(res_indices[i])
            res_name = res_names_dict.get(res_idx, "MOL")
            res_num = res_idx + 1 # Convert to 1-indexed for structural file formats

            # 2. Instantiate RDKit's structural record container
            res_info = AtomPDBResidueInfo(
                atomName=atom_name.ljust(4), # Standard PDB atom names are 4-chars wide
                residueName=res_name[:3].upper(), # Keeps it standardized to PDB (3 chars max)
                residueNumber=res_num,
                chainId="A" # Default chain assignment since MOL2/Arrays lack it
            )

            # 3. Permanently bind the residue attributes onto the RDKit atom 
            atom.SetMonomerInfo(res_info)

        return mol


    def Update(self,ene,crds,frcs):
        """
        Set the energy, positions, and forces

        Parameters
        ----------
        ene : float
            Energy in eV

        crds : list of list or N,3 numpy array
            The atomic coordinates in Angstrom.
            This will be internally converted to plain lists.

        frcs : list of list or N,3 numpy array, optional
            The atomic forces in eV/Angstrom.
            If forces are unavailable, set to None

        Returns
        -------
        None
        """
        self.data["energy"] = ene
        try:
            self.data["positions"] = crds.tolist()
        except:
            self.data["positions"] = crds
        self.data["forces"] = None
        if frcs is not None:
            try:
                self.data["forces"] = frcs.tolist()
            except:
                self.data["forces"] = frcs


