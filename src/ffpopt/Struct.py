    def GetFunctionalGroupCharges(self):
        """
        Get a dict of functional group charges

        Parameters
        ----------
        None

        Returns
        -------
        fgq : dict of list of float
             key: str, functional group name
             value: list of dict, each element is a distinct
                 functional group. The float is the sum of
                 atomic charges within the functional group.
        """
        from collections import defaultdict as ddict
        fg = self.GetFunctionalGroups()
        fgq = ddict(list)
        for key in fg:
            fgq[key] = [ self.GetChargeSum(idxs)
                         for idxs in fg[key] ]
        return fgq

    
    def GetChargeSum(self,idxs):
        """
        Get the sum of selected atomic charges

        Parameters
        ----------
        idxs : list of int
            The 0-based atom indexes

        Returns
        -------
        sumqs : float
            The net partial sum of atomic charges
        """
        qs = [ self.data["charges"][idx] for idx in idxs ]
        return sum(qs)


